export const UI_MESSAGES: Record<UiLocale, Record<MessageKey, string>> = { zh, en }

/** 插值：把模板里的 {name} 占位替换为 params 中的值；未提供的占位保持原样。 */
export function translate(locale: UiLocale, key: MessageKey, params?: Record<string, string | number>): string {
  const template = UI_MESSAGES[locale][key]
  if (!params) return template
  let result = template
  for (const [name, value] of Object.entries(params)) {
    result = result.replaceAll(`{${name}}`, String(value))
  }
  return result
}

/** 各方案新手指南的文案键；链接 href 等语言无关数据仍由 scheme-guides.ts 提供。 */
export interface SchemeGuideKeys {
  title: MessageKey
  tagline: MessageKey
  steps: MessageKey[]
  links: MessageKey[]
}

/** 按统一的 guide.<type>.step.N 命名规则生成一份方案指南文案键。 */
function guideKeys(type: SchemeType, stepCount: number, linkCount: number): SchemeGuideKeys {
  const numbered = (part: string, count: number) =>
    Array.from({ length: count }, (_, i) => `guide.${type}.${part}.${i + 1}`) as MessageKey[]
  return {
    title: `guide.${type}.title` as MessageKey,
    tagline: `guide.${type}.tagline` as MessageKey,
    steps: numbered('step', stepCount),
    links: numbered('link', linkCount),
  }
}

